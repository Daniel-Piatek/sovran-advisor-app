// The app icon, from its one source: design/icon.svg, containing the owner's supplied
// logo unchanged. Tokens supply the tile surround. scripts/build-icons.js
// writes the files. Two shapes come out of the one source:
//   round  the icon as drawn, with see-through corners (browser tab, desktop, Android)
//   tile   the icon on a full square of the ring colour, for systems that cut their own
//          shape out of the picture (iPhone home screen, Android "maskable")

import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

export const root = fileURLToPath(new URL('../', import.meta.url));
export const sourceFile = `${root}design/icon.svg`;
export const tokensFile = `${root}public/tokens.css`;
export const outDir = `${root}public/icons/`;
export const appName = 'Sovran Advisor';

// The light theme's tokens (the first :root block), with references to other tokens resolved.
export function readTokens(css = fs.readFileSync(tokensFile, 'utf8')) {
  const block = css.replace(/\/\*[\s\S]*?\*\//g, '').match(/:root\s*{([^}]*)}/)[1];
  const raw = Object.fromEntries([...block.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
  const resolve = (value, depth = 0) =>
    depth > 5 ? value : value.replace(/var\((--[\w-]+)\)/g, (_, name) => resolve(raw[name] ?? '', depth + 1));
  return Object.fromEntries(Object.entries(raw).map(([name, value]) => [name, resolve(value)]));
}

const iconTokens = (tokens) => Object.entries(tokens).filter(([name]) => name.startsWith('--icon-'));

function drawing(source) {
  return source.replace(/<!--[\s\S]*?-->/g, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].trim();
}

function withColours(tokens, body) {
  const vars = iconTokens(tokens).map(([name, value]) => `${name}: ${value};`).join(' ');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 300 300">\n` +
    // No "--" in an XML comment: it would make the file unreadable.
    `<!-- Generated by npm run icons from design/icon.svg and the icon tokens. Do not edit. -->\n` +
    `<style>svg { ${vars} }</style>\n${body}\n</svg>\n`;
}

export function roundSvg(source = fs.readFileSync(sourceFile, 'utf8'), tokens = readTokens()) {
  return withColours(tokens, drawing(source));
}

// The whole icon at 80% inside a square of the ring colour: the 80% is the "safe zone"
// that Android keeps whatever shape it cuts.
export function tileSvg(source = fs.readFileSync(sourceFile, 'utf8'), tokens = readTokens()) {
  return withColours(tokens,
    `<rect width="300" height="300" style="fill: var(--icon-base)"/>\n` +
    `<g transform="translate(30 30) scale(0.8)">\n${drawing(source)}\n</g>`);
}

